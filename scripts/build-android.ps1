param([string]$JdkPath = $env:TALA_JAVA_HOME, [string]$SdkPath = $env:ANDROID_HOME, [switch]$VerboseGradle, [switch]$Diagnostics)
$ErrorActionPreference = 'Stop'
$repoPath = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path
Set-Location -LiteralPath $repoPath
$versionCheck = & node 'scripts/check-android-version.cjs'
if ($LASTEXITCODE -ne 0) { throw 'Android release version validation failed.' }
$releaseVersion = $versionCheck | ConvertFrom-Json
Write-Output "Version checked: $($releaseVersion.version) (Android code $($releaseVersion.versionCode), $($releaseVersion.mode))"
$appConfig = (Get-Content -LiteralPath 'apps/scanner/app.json' -Raw | ConvertFrom-Json).expo
$variant = if ($Diagnostics) { 'debug' } else { 'release' }
$taskVariant = if ($Diagnostics) { 'Debug' } else { 'Release' }
$suffix = if ($Diagnostics) { '-diagnostics' } else { '' }
$evidencePrefix = if ($Diagnostics) { 'diagnostics-' } else { '' }
$apkPath = Join-Path $repoPath ('output/android/TALA-' + $appConfig.version + $suffix + '.apk')
# Refuse a signing change rather than suggesting an uninstall that would erase drafts.
$previousSignature = Get-Content -LiteralPath 'docs/evidence/apk-signature.txt' -Raw
$certificatePattern = 'Signer #1 certificate SHA-256 digest: ([a-fA-F0-9]+)'
$expectedCertificate = [regex]::Match($previousSignature, $certificatePattern).Groups[1].Value
if (-not $expectedCertificate) { throw 'The previous signing certificate evidence is missing. Verify it before building an upgrade.' }
if (-not $JdkPath) {
  $cachedJdk = Join-Path $env:USERPROFILE '.gradle\jdks\eclipse_adoptium-21-amd64-windows.2'
  if (Test-Path -LiteralPath (Join-Path $cachedJdk 'bin\java.exe')) { $JdkPath = $cachedJdk } else { $JdkPath = $env:JAVA_HOME }
}
if (-not (Test-Path -LiteralPath (Join-Path $JdkPath 'bin\java.exe'))) { throw 'Set TALA_JAVA_HOME to JDK 17 or 21.' }
if (-not $SdkPath) { $SdkPath = $env:ANDROID_SDK_ROOT }
if (-not $SdkPath -or -not (Test-Path -LiteralPath (Join-Path $SdkPath 'platform-tools'))) { throw 'Set ANDROID_HOME to the Android SDK.' }
$env:JAVA_HOME = $JdkPath
$env:ANDROID_HOME = $SdkPath
$env:ANDROID_SDK_ROOT = $SdkPath
$env:CI = '1'
$env:NODE_ENV = 'production'
$env:EXPO_OFFLINE = '1'
$env:ANDROID_USER_HOME = Join-Path $repoPath '.cache/android'
$env:DEBUG = ''
& npm.cmd run prepare:android
if ($LASTEXITCODE -ne 0) { throw 'Expo prebuild failed.' }
$sdkLine = 'sdk.dir=' + ($SdkPath -replace '\\', '/')
Set-Content -LiteralPath 'apps/scanner/android/local.properties' -Value $sdkLine -Encoding ASCII
$toolchain = Get-Content -LiteralPath 'apps/scanner/android-toolchain.json' -Raw | ConvertFrom-Json
$wrapperProperties = @(
  'distributionBase=GRADLE_USER_HOME',
  'distributionPath=wrapper/dists',
  ('distributionUrl=https\://services.gradle.org/distributions/gradle-' + $toolchain.gradle + '-bin.zip'),
  ('distributionSha256Sum=' + $toolchain.distributionSha256),
  'networkTimeout=120000',
  'validateDistributionUrl=true',
  'zipStoreBase=GRADLE_USER_HOME',
  'zipStorePath=wrapper/dists'
)
Set-Content -LiteralPath 'apps/scanner/android/gradle/wrapper/gradle-wrapper.properties' -Value $wrapperProperties -Encoding ASCII
Push-Location 'apps/scanner/android'
try {
  # Release task embeds the JS bundle and assets. Pilot-only debug signing is generated by Expo.
  $gradleArguments = @((':app:assemble' + $taskVariant), '-PreactNativeArchitectures=arm64-v8a,armeabi-v7a', '-Dorg.gradle.workers.max=2', '--no-daemon', '--console=plain')
  if ($Diagnostics) { $gradleArguments += '-PtalaOfflineDebug=true' }
  if ($VerboseGradle) { $gradleArguments += '--info' }
  & .\gradlew.bat @gradleArguments | Tee-Object -FilePath (Join-Path $repoPath ('docs/evidence/' + $evidencePrefix + 'android-build.log'))
  if ($LASTEXITCODE -ne 0) { throw 'Android build failed.' }
} finally { Pop-Location }
New-Item -ItemType Directory -Force 'output/android' | Out-Null
Copy-Item -LiteralPath ('apps/scanner/android/app/build/outputs/apk/' + $variant + '/app-' + $variant + '.apk') -Destination $apkPath -Force
$apkHash = (Get-FileHash -LiteralPath $apkPath -Algorithm SHA256).Hash.ToLowerInvariant()
$signature = & (Join-Path $SdkPath 'build-tools/36.0.0/apksigner.bat') verify --verbose --print-certs $apkPath
if ($LASTEXITCODE -ne 0) { throw 'APK signature verification failed.' }
$actualCertificate = [regex]::Match(($signature -join "`n"), $certificatePattern).Groups[1].Value
if (-not $actualCertificate -or $actualCertificate -ne $expectedCertificate) { throw 'The signing certificate changed. Do not uninstall the existing app; recover the original signing identity.' }
$signature | Set-Content -LiteralPath ('docs/evidence/' + $evidencePrefix + 'apk-signature.txt') -Encoding UTF8
$badging = & (Join-Path $SdkPath 'build-tools/36.0.0/aapt.exe') dump badging $apkPath
if ($LASTEXITCODE -ne 0) { throw 'APK identity inspection failed.' }
$identity = $badging | Select-Object -First 1
if ($identity -notmatch ([regex]::Escape("name='$($appConfig.android.package)'")) -or
    $identity -notmatch ([regex]::Escape("versionCode='$($appConfig.android.versionCode)'")) -or
    $identity -notmatch ([regex]::Escape("versionName='$($appConfig.version)'"))) { throw 'APK package/version differs from app.json.' }
$badging | Set-Content -LiteralPath ('docs/evidence/' + $evidencePrefix + 'apk-badging.txt') -Encoding UTF8
& python 'scripts/inspect_apk.py' $apkPath ('docs/evidence/' + $evidencePrefix + 'apk-inspection.json')
if ($LASTEXITCODE -ne 0) { throw 'APK content verification failed.' }
$finalVersionCheck = & node 'scripts/check-android-version.cjs'
if ($LASTEXITCODE -ne 0) { throw 'Post-build version validation failed.' }
$finalVersion = $finalVersionCheck | ConvertFrom-Json
if ($finalVersion.sourceFingerprint -ne $releaseVersion.sourceFingerprint) { throw 'Application source changed during the build. Rebuild before distributing this APK.' }
@{
  command = 'npm.cmd run build:android'; exitCode = 0; status = 'Pass'; gradle = $toolchain.gradle
  diagnosticsEnabled = [bool]$Diagnostics; offlineEmbeddedBundle = $true
  appVersion = $appConfig.version; versionCode = $appConfig.android.versionCode; apkSha256 = $apkHash
  signingCertificateSha256 = $actualCertificate; upgradeSignatureMatches = $true
  sourceFingerprint = $releaseVersion.sourceFingerprint
  physicalPhoneChecks = 'Not run'; testPhone = 'Samsung Galaxy A53 5G'
} | ConvertTo-Json | Set-Content -LiteralPath ('docs/evidence/' + $evidencePrefix + 'build-result.json') -Encoding UTF8
Write-Output "APK: $apkPath"
Write-Output "SHA-256: $apkHash"
