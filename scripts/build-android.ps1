param([string]$JdkPath = $env:TALA_JAVA_HOME, [string]$SdkPath = $env:ANDROID_HOME, [switch]$VerboseGradle)
$ErrorActionPreference = 'Stop'
$repoPath = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path
Set-Location -LiteralPath $repoPath
if (-not $JdkPath) {
  $cachedJdk = Join-Path $env:USERPROFILE '.gradle\jdks\eclipse_adoptium-21-amd64-windows.2'
  if (Test-Path -LiteralPath (Join-Path $cachedJdk 'bin\java.exe')) { $JdkPath = $cachedJdk } else { $JdkPath = $env:JAVA_HOME }
}
if (-not (Test-Path -LiteralPath (Join-Path $JdkPath 'bin\java.exe'))) { throw 'Set TALA_JAVA_HOME to JDK 17 or 21.' }
if (-not $SdkPath) { $SdkPath = $env:ANDROID_SDK_ROOT }
if (-not $SdkPath -or -not (Test-Path -LiteralPath (Join-Path $SdkPath 'platform-tools'))) { throw 'Set ANDROID_HOME to the Android SDK.' }
$env:JAVA_HOME = $JdkPath
$env:ANDROID_HOME = $SdkPath
$env:ANDROID_SDK_ROOT = $SdkPath
$env:CI = '1'
$env:NODE_ENV = 'production'
$env:EXPO_OFFLINE = '1'
$env:ANDROID_USER_HOME = Join-Path $repoPath '.cache/android'
$env:DEBUG = ''
& npm.cmd run prepare:android
if ($LASTEXITCODE -ne 0) { throw 'Expo prebuild failed.' }
$sdkLine = 'sdk.dir=' + ($SdkPath -replace '\\', '/')
Set-Content -LiteralPath 'apps/scanner/android/local.properties' -Value $sdkLine -Encoding ASCII
$toolchain = Get-Content -LiteralPath 'apps/scanner/android-toolchain.json' -Raw | ConvertFrom-Json
$wrapperProperties = @(
  'distributionBase=GRADLE_USER_HOME',
  'distributionPath=wrapper/dists',
  ('distributionUrl=https\://services.gradle.org/distributions/gradle-' + $toolchain.gradle + '-bin.zip'),
  ('distributionSha256Sum=' + $toolchain.distributionSha256),
  'networkTimeout=120000',
  'validateDistributionUrl=true',
  'zipStoreBase=GRADLE_USER_HOME',
  'zipStorePath=wrapper/dists'
)
Set-Content -LiteralPath 'apps/scanner/android/gradle/wrapper/gradle-wrapper.properties' -Value $wrapperProperties -Encoding ASCII
Push-Location 'apps/scanner/android'
try {
  # Release task embeds the JS bundle and assets. Pilot-only debug signing is generated by Expo.
  $gradleArguments = @(':app:assembleRelease', '-PreactNativeArchitectures=arm64-v8a,armeabi-v7a', '-Dorg.gradle.workers.max=2', '--no-daemon', '--console=plain')
  if ($VerboseGradle) { $gradleArguments += '--info' }
  & .\gradlew.bat @gradleArguments | Tee-Object -FilePath (Join-Path $repoPath 'docs/evidence/android-build.log')
  if ($LASTEXITCODE -ne 0) { throw 'Android build failed.' }
} finally { Pop-Location }
New-Item -ItemType Directory -Force 'output/android' | Out-Null
Copy-Item -LiteralPath 'apps/scanner/android/app/build/outputs/apk/release/app-release.apk' -Destination 'output/android/TALA-Phase1-0.1.0.apk' -Force
Get-FileHash -LiteralPath 'output/android/TALA-Phase1-0.1.0.apk' -Algorithm SHA256 | Format-List
& python 'scripts/inspect_apk.py'
if ($LASTEXITCODE -ne 0) { throw 'APK content verification failed.' }
